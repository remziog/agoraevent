#!/usr/bin/env bash
# Install the exact dependency versions Lovable uses, from outside Lovable
# (your machine, CI, mobile builds).
#
# bun.lock pins every tarball URL to Lovable's private registry mirror, which
# answers 403 everywhere else — so a plain `bun install` fails. The mirror serves
# the same tarballs as registry.npmjs.org (bun verifies the sha512 integrity of
# each one), so for this install only we point the URLs at npmjs and restore the
# lockfile afterwards. Never commit the rewritten lockfile: Lovable needs its own.
#
# Exact versions matter: the mobile app calls the production server functions by
# ID, and those IDs must be generated by the same TanStack Start version.
set -euo pipefail
cd "$(dirname "$0")/.."

cp bun.lock bun.lock.lovable
trap 'mv -f bun.lock.lovable bun.lock' EXIT

# -i.bak works with both GNU sed (Linux) and BSD sed (macOS)
sed -i.bak 's#https://europe-west4-npm.pkg.dev/lovable-core-prod/sandbox-npm-cache/#https://registry.npmjs.org/#g' bun.lock
rm -f bun.lock.bak

bun install --frozen-lockfile
